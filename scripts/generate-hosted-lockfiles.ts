// Generate the lockfiles a hosted source's sandbox installs from (#617 P4,
// criterion L): one for each hosted manifest entry's pinned package, one for
// the bridge's packages. Writes `src/lib/mcp/hosting/lockfiles.generated.ts`.
//
// WHEN TO RUN IT. Whenever a hosted source's pin moves (the router manifest's
// `hosting.version`, through a router bump) or `BRIDGE_PACKAGES` moves
// (`src/lib/mcp/hosting/bridge-source.ts`). `lockfiles.test.ts` fails until it
// has been re-run, because each lockfile's root must equal the pin it was
// resolved for. Commit the generated module with the move.
//
// WHAT IT DOES. For each directory the sandbox installs, it writes the same
// `package.json` the lifecycle writes (`install-manifests.ts`, `bridge-source.ts`) into an empty
// temporary directory and runs `npm install --package-lock-only
// --ignore-scripts` there against the public registry, by flag, so a
// developer's configured mirror never reaches a lockfile: the sandbox may
// reach `registry.npmjs.org` only while it installs. No package is
// downloaded into the repository and no install script runs.
//
// Run with:
//   node --experimental-strip-types scripts/generate-hosted-lockfiles.ts
//
// It needs the network (the public npm registry) and nothing else: no
// credential, no environment variable.

import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CIVIC_MANIFEST } from '@typedstandards/civic-typed-router';
import { BRIDGE_PACKAGE_JSON } from '../src/lib/mcp/hosting/bridge-source.ts';
import { pinLockfileKey, pinPackageJson, type NpmLockfile } from '../src/lib/mcp/hosting/install-manifests.ts';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(REPO, 'src/lib/mcp/hosting/lockfiles.generated.ts');
const REGISTRY = 'https://registry.npmjs.org/';

function resolveLockfile(packageJson: string): NpmLockfile {
  const dir = mkdtempSync(path.join(tmpdir(), 'hosted-lockfile-'));
  try {
    writeFileSync(path.join(dir, 'package.json'), packageJson);
    execFileSync('npm', ['install', '--package-lock-only', '--ignore-scripts', '--no-audit', '--no-fund', `--registry=${REGISTRY}`], {
      cwd: dir,
      stdio: ['ignore', 'ignore', 'inherit'],
    });
    return JSON.parse(readFileSync(path.join(dir, 'package-lock.json'), 'utf8')) as NpmLockfile;
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const pins: Record<string, NpmLockfile> = {};
for (const entry of CIVIC_MANIFEST) {
  if (!entry.hosting) continue;
  pins[pinLockfileKey(entry.hosting)] = resolveLockfile(pinPackageJson(entry.hosting));
}
const bridge = resolveLockfile(BRIDGE_PACKAGE_JSON);

const count = (lock: NpmLockfile) => Object.keys(lock.packages).length - 1;
const header = [
  '// GENERATED by scripts/generate-hosted-lockfiles.ts. Do not edit by hand:',
  '// re-run the script when a hosted pin or BRIDGE_PACKAGES moves (#617 P4).',
  '//',
  '// The lockfiles a hosted source\'s sandbox installs from with',
  '// `npm ci --ignore-scripts`: one per hosted pin, keyed `<package>@<version>`,',
  '// and one for the bridge. A module rather than files, so the deployment',
  '// bundles them and nothing is read from disk at run time.',
  `//   ${Object.entries(pins).map(([key, lock]) => `${key}: ${count(lock)} packages`).join('; ')}; bridge: ${count(bridge)} packages`,
  '',
  "import type { NpmLockfile } from './install-manifests.ts';",
  '',
];
const body = [
  `export const PIN_LOCKFILES: Readonly<Record<string, NpmLockfile>> = ${JSON.stringify(pins, null, 2)};`,
  '',
  `export const BRIDGE_LOCKFILE: NpmLockfile = ${JSON.stringify(bridge, null, 2)};`,
  '',
];
writeFileSync(OUT, [...header, ...body].join('\n'));
console.log(`wrote ${path.relative(REPO, OUT)}: ${Object.keys(pins).length} pin lockfile(s), bridge ${count(bridge)} packages`);
